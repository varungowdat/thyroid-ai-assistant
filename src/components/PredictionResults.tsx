import { PredictionResult } from '../types';
import RiskGauge from './RiskGauge';
import { CheckCircle, AlertTriangle, XCircle, Download } from 'lucide-react';

interface PredictionResultsProps {
  recurrence: PredictionResult | null;
  response: PredictionResult | null;
}

export default function PredictionResults({ recurrence, response }: PredictionResultsProps) {
  if (!recurrence || !response) {
    return null;
  }

  const getRecurrenceIcon = () => {
    if (recurrence.prediction === 'No') {
      return <CheckCircle className="h-12 w-12 text-green-500" />;
    }
    return <AlertTriangle className="h-12 w-12 text-red-500" />;
  };

  const getResponseIcon = () => {
    if (response.prediction === 'Excellent') {
      return <CheckCircle className="h-12 w-12 text-green-500" />;
    } else if (response.prediction === 'Indeterminate') {
      return <AlertTriangle className="h-12 w-12 text-yellow-500" />;
    }
    return <XCircle className="h-12 w-12 text-red-500" />;
  };

  const handleDownloadReport = () => {
    const report = `
THYROID AI ASSISTANT - PREDICTION REPORT
========================================

Date: ${new Date().toLocaleDateString()}

RECURRENCE PREDICTION
---------------------
Result: ${recurrence.prediction}
Probability: ${recurrence.probability.toFixed(1)}%
Confidence: ${recurrence.confidence.toFixed(1)}%
Explanation: ${recurrence.explanation}

TREATMENT RESPONSE PREDICTION
-----------------------------
Result: ${response.prediction}
Probability: ${response.probability.toFixed(1)}%
Confidence: ${response.confidence.toFixed(1)}%
Explanation: ${response.explanation}

DISCLAIMER
----------
This prediction is generated by machine learning models and should not replace
professional medical advice. Always consult with your healthcare provider for
diagnosis and treatment decisions.
    `.trim();

    const blob = new Blob([report], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `thyroid-prediction-report-${new Date().getTime()}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6 animate-fadeIn">
      <div className="flex justify-between items-center">
        <h2 className="text-2xl font-bold text-gray-900">Prediction Results</h2>
        <button
          onClick={handleDownloadReport}
          className="flex items-center gap-2 px-4 py-2 bg-blue-600 text-white rounded-lg hover:bg-blue-700 transition-colors"
        >
          <Download className="h-4 w-4" />
          Download Report
        </button>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        <div className="bg-white p-6 rounded-lg shadow-md border border-gray-200">
          <div className="flex items-center gap-4 mb-4">
            {getRecurrenceIcon()}
            <div>
              <h3 className="text-xl font-semibold text-gray-900">Recurrence Risk</h3>
              <p className="text-3xl font-bold text-gray-800 mt-1">{recurrence.prediction}</p>
            </div>
          </div>

          <div className="space-y-4 mt-6">
            <RiskGauge
              percentage={recurrence.probability}
              label="Recurrence Probability"
              prediction={recurrence.prediction}
            />
            <div className="pt-4 border-t border-gray-200">
              <p className="text-sm text-gray-600 leading-relaxed">{recurrence.explanation}</p>
            </div>
          </div>
        </div>

        <div className="bg-white p-6 rounded-lg shadow-md border border-gray-200">
          <div className="flex items-center gap-4 mb-4">
            {getResponseIcon()}
            <div>
              <h3 className="text-xl font-semibold text-gray-900">Treatment Response</h3>
              <p className="text-3xl font-bold text-gray-800 mt-1">{response.prediction}</p>
            </div>
          </div>

          <div className="space-y-4 mt-6">
            <RiskGauge
              percentage={response.probability}
              label="Response Probability"
              prediction={response.prediction}
            />
            <div className="pt-4 border-t border-gray-200">
              <p className="text-sm text-gray-600 leading-relaxed">{response.explanation}</p>
            </div>
          </div>
        </div>
      </div>

      <div className="bg-yellow-50 border border-yellow-200 rounded-lg p-4">
        <p className="text-sm text-yellow-800">
          <strong>Disclaimer:</strong> These predictions are generated by machine learning models trained on clinical data.
          They should not replace professional medical advice. Always consult with your healthcare provider for diagnosis
          and treatment decisions.
        </p>
      </div>
    </div>
  );
}
